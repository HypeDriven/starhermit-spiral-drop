/** Today's Daily by keys at 1024 × 640, to its results (won or not: the plan's outcome). */
export function dailyScript(date) {
  const d = C.dailyFor(date);
  const p = run(d, 'daily');
  return header([
    `# Today's Daily (${d.day}) by keys from the bot's plan (${p.terminal.reason}, ${p.total} points). Written by tests/native.mjs.`,
    '# viewport 1024x640@1',
    'until 600 Spiral Drop',
    'frames 30',
    'click =Daily Drop',
    'until 120 =Start',
    'frames 10',
    'click =Start',
    'until 300 =3',
    ...keyLines(p.dirs),
    ...results(p),
    'save daily-results',
  ]);
}

