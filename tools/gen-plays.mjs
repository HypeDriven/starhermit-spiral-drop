// Writes the native play scripts (tests/native/*.play) from runs the rules
// play here: the planning bot (tools/bot.mjs) rotates on the client's fixed
// steps (one rules tick a 60 Hz step), and its rotation changes become hold /
// release lines at exact frames. Timing on the 1.20.2 render check
// (measured): the `until =3` line matches on the frame the countdown shows
// its first beat; the first active step is FIRST_STEP frames later; each key
// line takes one frame and acts on that frame's step; `frames N` takes N + 1
// frames. Each scripted run then expects the planned total on the results.
//   node tools/gen-plays.mjs            (writes the committed scripts)
// dailyScript(date) is used by tests/native.mjs for today's Daily.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { plan, stepWith, R, C } from './bot.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export let FIRST_STEP = Number(process.env.FIRST_STEP || 159);

const KEY = { '-1': 'ArrowLeft', 1: 'ArrowRight' };
/** The key lines after `until =3` that hold `dirs` step by step. */
export function keyLines(dirs) {
  const out = [];
  let c = 0; // frames since the `until` frame
  let prev = 0;
  const at = (f) => {
    const g = f - c - 1;
    if (g < 0) throw new Error(`two key lines in one frame at ${f}`);
    if (g > 0) out.push(`frames ${g - 1}`);
    c = f;
  };
  dirs.forEach((d, k) => {
    if (d === prev) return;
    if (prev !== 0 && d !== 0) throw new Error(`step ${k}: reversal without release`);
    at(FIRST_STEP + k);
    out.push(prev !== 0 ? `release ${KEY[prev]}` : `hold ${KEY[d]}`);
    prev = d;
  });
  if (prev !== 0) { at(FIRST_STEP + dirs.length); out.push(`release ${KEY[prev]}`); }
  return out;
}
const cfgOf = (content, mode, allowUndo = false) => C.toConfig(content, { mode, allowUndo });
function run(content, mode, allowUndo = false, opts) {
  const p = plan(cfgOf(content, mode, allowUndo), opts);
  if (!p.terminal) throw new Error(`${content.id}: no end`);
  return p;
}
const header = (lines) => lines.join('\n') + '\n';
const results = (p) => ['until 600 Score breakdown', 'frames 10', `expect =${p.total}`];

/** Journey stages 1–4 by keys on a desktop, each to its results and "Next". */
function journeyScript() {
  const stages = C.journeyStages();
  const lines = [
    '# Generated by tools/gen-plays.mjs: Journey stages 1-4 by keys on a desktop (the bot\'s plans as held arrows),',
    '# each to its results with the planned total, then the next stage; stage 4 ends with the replay watched to the title.',
    '# viewport 1280x800@1',
    'until 600 Spiral Drop',
    'frames 30',
    'click ▶ Play — start the Journey',
    'until 120 =Start',
    'frames 10',
    'click =Start',
  ];
  for (let i = 0; i < 4; i++) {
    const st = stages[i];
    const p = run(st, 'journey');
    if (p.terminal.reason !== 'completed') throw new Error(`${st.id} lost`);
    lines.push(`# ${st.id} ${st.name}: ${p.dirs.length} steps, ${p.total} points`, 'until 300 =3', ...keyLines(p.dirs), ...results(p));
    if (i === 0) lines.push('expect First Descent', 'save journey-results');
    if (i < 3) lines.push(`click Next: ${stages[i + 1].name}`);
  }
  lines.push('click Watch replay', 'until 120 Replay', 'frames 100', 'save journey-replay', 'until 2000 Daily Drop', 'frames 10', 'click =Journey',
    'until 120 Mastery stages glow gold', 'frames 10', 'expect 4 / 40 stages cleared', 'save journey-map');
  return header(lines);
}

/** Lessons 1 and 2 on a DPR-3 phone: menus by finger, lesson 1's rotation goal by a sideways swipe, the rest by keys. */
function lessonScript() {
  const [l1, l2] = C.LESSONS;
  // lesson 1: hold right until the goal (90 ticks of turning), then the bot to the base
  // turn back and forth beside the gap until 95 ticks of turning, then let the bot drop to the base
  let away = true;
  const p1 = run(l1, 'learn', true, {
    force: (s) => {
      if (s.stats.rotationTicks >= 95 || s.phase !== 'rest') return null;
      const al = R.gapAlignment(s, s.ball.layer + 1);
      const half = s.config.layers[s.ball.layer + 1].gapWidth / 2;
      if (away && Math.abs(al.delta) > 2.4) away = false;
      else if (!away && Math.abs(al.delta) < half + 0.35) away = true;
      return (al.delta > 0) === away ? 1 : -1;
    },
  });
  if (p1.state.stats.rotationTicks < 90) throw new Error('lesson 1 goal not reached');
  const p2 = run(l2, 'learn', true);
  return header([
    '# Generated by tools/gen-plays.mjs: Learn on a DPR-3 phone — the lesson list and setup by finger, lesson 1\'s',
    '# rotation goal (and the base) by keys, lesson 2 to the base; then a swipe on the tower in a third run and pause by finger.',
    '# viewport 390x844@3',
    'until 600 Spiral Drop',
    'frames 30',
    'touch =Learn to Play',
    'until 120 One rule at a time',
    'frames 10',
    'touch 1. Rotate the Tower',
    'until 120 =Start',
    'frames 10',
    'touch =Start',
    'until 300 =3',
    ...keyLines(p1.dirs),
    ...results(p1),
    'save lesson-results',
    'touch ← Menu',
    'until 120 Daily Drop',
    'frames 10',
    'touch =Learn to Play',
    'until 120 One rule at a time',
    'frames 10',
    'expect ✓ 1. Rotate the Tower',
    'touch 2. Find the Gap',
    'until 120 =Start',
    'frames 10',
    'touch =Start',
    'until 300 =3',
    ...keyLines(p2.dirs),
    ...results(p2),
    'touch =Retry',
    'until 300 =3',
    'frames 170',
    'touch Pause (Esc)',
    'until 60 =Resume',
    'frames 10',
    'save lesson-pause',
    'touch =Resume',
    'frames 30',
    '# a finger dragged sideways over the tower turns it: swipes alone take the ball to the base',
    'repeat 3000 until Score breakdown',
    'swipe 25% 55% 85% 55% 30',
    'frames 20',
    'end',
    'frames 10',
    'expect Base Reached!',
    'save lesson-swipe',
    'touch ← Menu',
    'until 120 Daily Drop',
  ]);
}

